console.log('Seeding products...');
const now = Date.now();
let inserted = 0;
let skipped = 0;

for (const p of products) {
  try {
    const existing = db.prepare('SELECT id FROM products WHERE id = ?').get(p.id);
    if (existing) {
      // Update existing
      db.prepare(`
        UPDATE products SET
          name = ?, category = ?, mrp = ?, pack_size = ?, image = ?, video = ?,
          short_description = ?, description = ?, highlights = ?, ingredients = ?,
          stock = ?, updated_at = ?
        WHERE id = ?
      `).run(
        p.name, p.category, p.mrp, p.packSize, p.image, p.video,
        p.shortDescription, p.description, p.highlights, p.ingredients,
        p.stock, now, p.id
      );
      console.log(`  Updated: ${p.id}`);
    } else {
      db.prepare(`
        INSERT INTO products (id, name, category, mrp, pack_size, image, video,
          short_description, description, highlights, ingredients, stock, created_at, updated_at)
        VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
      `).run(
        p.id, p.name, p.category, p.mrp, p.packSize, p.image, p.video,
        p.shortDescription, p.description, p.highlights, p.ingredients,
        p.stock, now, now
      );
      console.log(`  Inserted: ${p.id}`);
      inserted++;
    }
  } catch (e) {
    console.error(`  Error with ${p.id}:`, e.message);
  }
}

const count = db.prepare('SELECT COUNT(*) as c FROM products').get();
console.log(`\nDone! Total products in database: ${count.c} (${inserted} new)`);